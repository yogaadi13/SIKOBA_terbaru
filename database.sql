CREATE DATABASE IF NOT EXISTS sikoba CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sikoba;

CREATE TABLE IF NOT EXISTS app_state (
 id TINYINT UNSIGNED PRIMARY KEY,
 state_json LONGTEXT NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS obat (
 id BIGINT UNSIGNED PRIMARY KEY,
 nama_obat VARCHAR(150) NOT NULL,
 jenis VARCHAR(50) NOT NULL,
 dosis VARCHAR(80) NULL,
 stok INT NOT NULL DEFAULT 0,
 stok_minimum INT NOT NULL DEFAULT 0,
 tanggal_kedaluwarsa DATE NULL,
 kategori VARCHAR(80) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_obat_nama(nama_obat)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS transaksi (
 id BIGINT UNSIGNED PRIMARY KEY,
 obat_id BIGINT UNSIGNED NOT NULL,
 jenis_transaksi ENUM('Masuk','Keluar') NOT NULL,
 jumlah INT NOT NULL,
 tanggal DATE NOT NULL,
 keterangan VARCHAR(255) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_tx_obat(obat_id),
 INDEX idx_tx_tanggal(tanggal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS petugas (
 id TINYINT UNSIGNED PRIMARY KEY,
 nama VARCHAR(150) NOT NULL,
 username VARCHAR(80) NOT NULL,
 email VARCHAR(150) NULL,
 no_hp VARCHAR(30) NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nama VARCHAR(150) NOT NULL,
 username VARCHAR(80) NOT NULL UNIQUE,
 email VARCHAR(150) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 no_hp VARCHAR(30) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS kategori_obat (
 id INT AUTO_INCREMENT PRIMARY KEY,
 nama VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS notifikasi (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 obat_id BIGINT UNSIGNED NULL,
 jenis VARCHAR(50) NOT NULL,
 pesan VARCHAR(255) NOT NULL,
 status_baca TINYINT(1) NOT NULL DEFAULT 0,
 dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_notif_obat(obat_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Akun demo dibuat otomatis oleh api.php saat pertama kali diakses.

-- Tabel tambahan untuk fitur Stok Opname
CREATE TABLE IF NOT EXISTS stok_opname (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nomor_opname VARCHAR(40) NOT NULL UNIQUE,
 tanggal DATE NOT NULL,
 keterangan VARCHAR(255) NULL,
 total_item INT NOT NULL DEFAULT 0,
 total_selisih INT NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL DEFAULT 'Selesai',
 dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_opname_tanggal(tanggal)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS detail_stok_opname (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 opname_id BIGINT UNSIGNED NOT NULL,
 obat_id BIGINT UNSIGNED NOT NULL,
 nama_obat VARCHAR(150) NOT NULL,
 stok_sistem INT NOT NULL,
 stok_fisik INT NOT NULL,
 selisih INT NOT NULL,
 CONSTRAINT fk_detail_opname_header FOREIGN KEY(opname_id)
   REFERENCES stok_opname(id) ON DELETE CASCADE,
 INDEX idx_detail_opname_obat(obat_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
